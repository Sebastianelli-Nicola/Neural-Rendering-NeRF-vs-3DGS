"""
Usage:

    python create_downscaled_depths.py \
        nerfstudio_dataset/<object>/depths

For example:

    python create_downscaled_depths.py \
        nerfstudio_dataset/cestino_medio/depths

This will create:

    depths_2/
    depths_4/
    depths_8/

next to the original `depths/` directory.

------

This script was used to generate the downscaled depth-map directories for
Nerfstudio datasets.

During dataset preparation, `ns-process-data` automatically generates
downscaled versions of the RGB images (e.g. `images_2`, `images_4`,
`images_8`) to improve training and data loading performance.

However, equivalent downscaled versions are not automatically generated for
custom depth maps. This script was therefore used to create the corresponding
downscaled depth directories starting from the processed depth maps stored in
the dataset `depths/` directory.

This script:
- Reads all PNG depth maps from the input `depths/` directory.
- Creates sibling directories such as `depths_2`, `depths_4`, and `depths_8`.
- Resizes each depth map according to the requested downscale factors.
- Preserves the original filenames.
- Saves the resized depth maps into the corresponding output directories.

For example:

    depths/frame_00001.png
    depths_2/frame_00001.png
    depths_4/frame_00001.png
    depths_8/frame_00001.png

Assumptions:
- The input `depths/` directory already contains the processed depth maps
  generated by `prepare_nerfstudio_depths.py`.
- The depth maps have already been renamed, rotated, and resized to match
  the RGB images contained in the Nerfstudio dataset.

The generated directory structure mirrors the RGB image pyramid generated
by `ns-process-data`.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image


RESAMPLING_MODES = {
    "nearest": Image.Resampling.NEAREST,
    "bilinear": Image.Resampling.BILINEAR,
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Create downscaled depth folders next to INPUT_DEPTH_DIR, such as "
            "depths_2, depths_4, and depths_8."
        )
    )
    parser.add_argument(
        "input_depth_dir",
        type=Path,
        help="Input depth folder containing PNG files.",
    )
    parser.add_argument(
        "--factors",
        type=int,
        nargs="+",
        default=[2, 4, 8],
        help="Downscale factors to create. Default: 2 4 8",
    )
    parser.add_argument(
        "--resample",
        choices=tuple(RESAMPLING_MODES),
        default="bilinear",
        help="Resize resampling mode. Default: bilinear",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing output files.",
    )
    return parser.parse_args()


def pngs_in_order(folder: Path) -> list[Path]:
    return sorted(folder.glob("*.png"), key=lambda path: path.name)


def validate_factors(factors: list[int]) -> None:
    invalid_factors = [factor for factor in factors if factor < 1]
    if invalid_factors:
        raise SystemExit(f"Downscale factors must be positive integers: {invalid_factors}")


def downscale_size(size: tuple[int, int], factor: int, image_path: Path) -> tuple[int, int]:
    width, height = size
    new_size = (width // factor, height // factor)
    if new_size[0] < 1 or new_size[1] < 1:
        raise SystemExit(
            f"Downscale factor {factor} is too large for {image_path}: "
            f"original size {size}, computed size {new_size}"
        )
    return new_size


def main() -> None:
    args = parse_args()
    input_depth_dir = args.input_depth_dir
    resample = RESAMPLING_MODES[args.resample]

    if not input_depth_dir.is_dir():
        raise SystemExit(f"Input depth directory does not exist: {input_depth_dir}")

    validate_factors(args.factors)
    depth_images = pngs_in_order(input_depth_dir)
    if not depth_images:
        raise SystemExit(f"No PNG files found in input depth directory: {input_depth_dir}")

    output_dirs = {
        factor: input_depth_dir.with_name(f"{input_depth_dir.name}_{factor}")
        for factor in args.factors
    }

    for output_dir in output_dirs.values():
        output_dir.mkdir(parents=True, exist_ok=True)

    examples: list[tuple[Path, dict[int, tuple[Path, tuple[int, int], tuple[int, int]]]]] = []

    for image_path in depth_images:
        try:
            with Image.open(image_path) as image:
                original_size = image.size

                image_examples: dict[int, tuple[Path, tuple[int, int], tuple[int, int]]] = {}
                for factor, output_dir in output_dirs.items():
                    output_path = output_dir / image_path.name
                    if output_path.exists() and not args.overwrite:
                        raise SystemExit(
                            f"Output file already exists: {output_path}. "
                            "Re-run with --overwrite to replace it."
                        )

                    target_size = downscale_size(original_size, factor, image_path)
                    resized_image = image.resize(target_size, resample=resample)
                    if resized_image.size != target_size:
                        raise SystemExit(
                            f"Output size mismatch for {output_path}: "
                            f"expected {target_size}, got {resized_image.size}"
                        )

                    resized_image.save(output_path)
                    image_examples[factor] = (output_path, original_size, resized_image.size)
        except OSError as error:
            raise SystemExit(f"Could not process depth image {image_path}: {error}") from error

        if len(examples) < 5:
            examples.append((image_path, image_examples))

    print(f"Input files: {len(depth_images)}")
    print(f"Input depth folder: {input_depth_dir}")
    print("Created output folders:")
    for factor, output_dir in output_dirs.items():
        print(f"  {factor}: {output_dir}")
    print("Example mappings:")
    for source_path, factor_examples in examples:
        for factor, (output_path, original_size, final_size) in factor_examples.items():
            print(
                f"  x{factor}: {source_path.name} -> {output_path.name}; "
                f"{original_size} -> {final_size}"
            )


if __name__ == "__main__":
    main()
